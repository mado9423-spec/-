// Self-hosts the three typefaces so the app makes no request to Google at run time (privacy, offline use, a stricter CSP).
//   node scripts/fetch-fonts.mjs        (needs network access to fonts.googleapis.com / fonts.gstatic.com; uses curl)
// Writes app/fonts/*.woff2 and src/fonts.css (Arabic + Latin subsets only). Licences: SIL Open Font License 1.1.
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';
const API = 'https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@500&family=IBM+Plex+Sans+Arabic:wght@400;500;600&family=Readex+Pro:wght@300;400;500;600;700&display=swap';
const curl = (url, out) => execFileSync('curl', ['-fsSL', '-A', UA, url, ...(out ? ['-o', out] : [])], { maxBuffer: 1 << 26 });

const css = curl(API).toString('utf8');
const KEEP = new Set(['arabic', 'latin']);
const blocks = [...css.matchAll(/\/\* ([\w-]+) \*\/\s*@font-face \{([\s\S]*?)\}/g)].map((m) => {
  const b = m[2];
  return { subset: m[1], family: /font-family: '([^']+)'/.exec(b)[1], weight: /font-weight: (\d+)/.exec(b)[1], url: /url\(([^)]+)\)/.exec(b)[1], range: /unicode-range: ([^;]+);/.exec(b)[1] };
}).filter((b) => KEEP.has(b.subset));

const outDir = join(root, 'app/fonts');
mkdirSync(outDir, { recursive: true });
const files = new Map(); // url -> local name
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-');
const rules = [];
const variable = new Set();
for (const b of blocks) {
  const shared = blocks.filter((x) => x.family === b.family && x.subset === b.subset && x.url === b.url);
  const isVar = shared.length > 1; // one file serves several weights: a variable font
  const key = `${b.family}|${b.subset}|${b.url}`;
  if (isVar && variable.has(key)) continue;
  if (isVar) variable.add(key);
  const name = `${slug(b.family)}-${isVar ? 'var' : b.weight}-${b.subset}.woff2`;
  if (!files.has(b.url)) { curl(b.url, join(outDir, name)); files.set(b.url, name); }
  const weights = isVar ? `${Math.min(...shared.map((x) => +x.weight))} ${Math.max(...shared.map((x) => +x.weight))}` : b.weight;
  rules.push(`@font-face{font-family:'${b.family}';font-style:normal;font-weight:${weights};font-display:swap;src:url(fonts/${files.get(b.url)}) format('woff2');unicode-range:${b.range}}`);
}
writeFileSync(join(root, 'src/fonts.css'), `/* generated by scripts/fetch-fonts.mjs: self-hosted subsets (Arabic + Latin) of Readex Pro, IBM Plex Sans Arabic and IBM Plex Mono (SIL OFL 1.1) */\n${rules.join('\n')}\n`);
console.log(`${files.size} font files, ${rules.length} rules`);
