// Regenerates the app icons from brand/mark.svg (the traced ship; no name inside the mark).
//   PW_ROOT=<dir containing node_modules/playwright> node scripts/make-icons.mjs     (PNG rendering needs Playwright)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const NAVY = '#1d2549';
const mark = readFileSync(join(root, 'brand/mark.svg'), 'utf8');
const vb = mark.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
const [mw, mh] = [parseFloat(vb[1]), parseFloat(vb[2])];
const d = mark.match(/ d="([^"]+)"/)[1];

/* a single-colour copy of the mark, for documents and dark/light backgrounds */
const single = (fill) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${mw} ${mh}" role="img" aria-label="Ship mark"><path fill="${fill}" fill-rule="evenodd" d="${d}"/></svg>\n`;
writeFileSync(join(root, 'brand/mark-navy.svg'), single(NAVY));
writeFileSync(join(root, 'brand/mark-gold.svg'), single('#d1a24d'));

/* app icon: champagne-gold tile, navy ship. `fit` is the share of the tile the mark may use */
const icon = (fit, radius) => {
  const w = 512 * fit, s = w / mw, h = mh * s;
  const tx = (512 - w) / 2, ty = (512 - h) / 2 + 6;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" role="img" aria-label="App icon">
  <defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#f4dca0"/><stop offset=".62" stop-color="#d1a24d"/><stop offset="1" stop-color="#9a6b22"/></linearGradient></defs>
  <rect width="512" height="512" rx="${radius}" fill="url(#g)"/>
  <g transform="translate(${tx.toFixed(2)} ${ty.toFixed(2)}) scale(${s.toFixed(4)})"><path fill="${NAVY}" fill-rule="evenodd" d="${d}"/></g>
</svg>
`;
};
/* the in-app mark: one source of truth (brand/mark.svg) -> src/js/03-logo.js */
writeFileSync(join(root, 'src/js/03-logo.js'), `/* generated by scripts/make-icons.mjs from brand/mark.svg: do not edit */\nconst LOGO_VB = '0 0 ${mw} ${mh}';\nconst LOGO_D = '${d}';\n`);
const out = join(root, 'app/icons');
mkdirSync(out, { recursive: true });
writeFileSync(join(out, 'icon.svg'), icon(0.64, 112));
writeFileSync(join(out, 'icon-maskable.svg'), icon(0.5, 0)); /* full-bleed; the OS applies its own mask, so keep the mark inside the safe zone */

if (process.env.PW_ROOT || process.argv.includes('--png')) {
  const { chromium } = process.env.PW_ROOT ? createRequire(process.env.PW_ROOT.replace(/\/?$/, '/'))('playwright') : await import('playwright');
  const browser = await chromium.launch({ args: ['--no-sandbox'] });
  for (const [src, name, size, transparent] of [['icon.svg', 'icon-192.png', 192, true], ['icon.svg', 'icon-512.png', 512, true], ['icon-maskable.svg', 'icon-maskable-512.png', 512, false], ['icon-maskable.svg', 'apple-touch-icon.png', 180, false]]) {
    const page = await browser.newPage({ viewport: { width: size, height: size } });
    await page.setContent(`<style>html,body{margin:0;background:transparent}svg{display:block;width:${size}px;height:${size}px}</style>${readFileSync(join(out, src), 'utf8')}`);
    await page.screenshot({ path: join(out, name), omitBackground: transparent, clip: { x: 0, y: 0, width: size, height: size } });
    await page.close();
  }
  await browser.close();
}
console.log('icons written');
